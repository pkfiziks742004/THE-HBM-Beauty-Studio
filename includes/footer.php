    <script>
    document.addEventListener('DOMContentLoaded', () => {
        // Initialize Lucide icons safely
        if (typeof lucide !== 'undefined' && typeof lucide.createIcons === 'function') {
            lucide.createIcons();
        }
        const audio = document.getElementById('hbm-bg-music');
        const toggleBtn = document.getElementById('hbm-music-toggle');
        
        if (!audio || !toggleBtn) return;
        
        // Pleasant default ambient volume
        audio.volume = 0.3;
        
        // Restore playback position in case of hard page reloads (multi-page routing support)
        const savedTime = sessionStorage.getItem('hbm_music_time');
        if (savedTime) {
            audio.currentTime = parseFloat(savedTime);
        }
        
        // Save playback position periodically
        setInterval(() => {
            if (!audio.paused && !audio.muted) {
                sessionStorage.setItem('hbm_music_time', audio.currentTime);
            }
        }, 1000);
        
        const storedPref = localStorage.getItem('hbm_music_pref');
        
        function updateUI(isPlaying) {
            if (isPlaying) {
                toggleBtn.classList.add('is-playing');
                toggleBtn.setAttribute('aria-label', 'Mute Music');
            } else {
                toggleBtn.classList.remove('is-playing');
                toggleBtn.setAttribute('aria-label', 'Play Music');
            }
        }

        // If user explicitly muted before, respect their choice globally
        if (storedPref === 'muted') {
            audio.pause();
            updateUI(false);
        } else {
            // Attempt autoplay
            const playPromise = audio.play();
            
            if (playPromise !== undefined) {
                playPromise.then(() => {
                    // Autoplay started successfully
                    updateUI(true);
                }).catch((error) => {
                    // Autoplay blocked by browser. Wait for first interaction.
                    updateUI(false);
                    
                    const startAudioOnInteract = () => {
                        // Only play if they haven't manually clicked the mute button in the meantime
                        if (localStorage.getItem('hbm_music_pref') !== 'muted') {
                            audio.play().then(() => {
                                updateUI(true);
                            }).catch(e => { /* Ignore errors if still blocked */ });
                        }
                        // Remove listeners after first interaction
                        document.removeEventListener('click', startAudioOnInteract);
                        document.removeEventListener('keydown', startAudioOnInteract);
                        document.removeEventListener('touchstart', startAudioOnInteract);
                    };
                    
                    document.addEventListener('click', startAudioOnInteract, { once: true });
                    document.addEventListener('keydown', startAudioOnInteract, { once: true });
                    document.addEventListener('touchstart', startAudioOnInteract, { once: true });
                });
            }
        }
        
        // User manual toggle click
        toggleBtn.addEventListener('click', (e) => {
            e.stopPropagation(); // Prevent triggering the first-interaction listener immediately
            
            if (audio.paused) {
                audio.play().then(() => {
                    updateUI(true);
                    localStorage.setItem('hbm_music_pref', 'playing');
                }).catch(err => console.log('Playback failed', err));
            } else {
                audio.pause();
                updateUI(false);
                localStorage.setItem('hbm_music_pref', 'muted');
            }
        });
    });
